SELECT
    CL.CLAIM_ID,
    CL.POLICY_ID,
    CL.CUSTOMER_ID,
    CL.CLAIM_DATE,
    CL.INCIDENT_DATE,
    CL.CLAIM_TYPE,
    CL.CLAIM_STATUS,
    CL.CLAIM_AMOUNT,
    CL.APPROVED_AMOUNT,
    CL.SETTLEMENT_DATE,

    P.POLICY_TYPE,
    P.POLICY_STATUS,
    P.POLICY_START_DATE,
    P.POLICY_END_DATE,
    P.PREMIUM_AMOUNT,
    P.COVERAGE_AMOUNT,
    P.CUSTOMER_ID AS POLICY_CUSTOMER_ID,
    P.AGENT_ID,

    C.FIRST_NAME,
    C.LAST_NAME,
    C.CUSTOMER_TYPE,

    CASE
        WHEN P.POLICY_ID IS NULL THEN 'POLICY_NOT_FOUND'
        WHEN C.CUSTOMER_ID IS NULL THEN 'CUSTOMER_NOT_FOUND'
        WHEN CL.CUSTOMER_ID <> P.CUSTOMER_ID
            THEN 'POLICY_CUSTOMER_MISMATCH'
        ELSE 'MATCHED'
    END AS CLAIM_RELATIONSHIP_STATUS,

    CL.SOURCE_FILE,
    CL.FILE_ROW_NUMBER,
    CL.LOAD_BATCH_ID,
    CL.SOURCE_SYSTEM,
    CL.RECORD_HASH

FROM {{ ref('stg_claim') }} CL

LEFT JOIN {{ ref('stg_policy') }} P
    ON CL.POLICY_ID = P.POLICY_ID

LEFT JOIN {{ ref('stg_customer') }} C
    ON CL.CUSTOMER_ID = C.CUSTOMER_ID

