SELECT
    PM.PAYMENT_ID,
    PM.CLAIM_ID,
    PM.POLICY_ID,
    PM.PAYMENT_AMOUNT,
    PM.PAYMENT_DATE,
    PM.PAYMENT_METHOD,
    PM.PAYMENT_STATUS,

    CL.CUSTOMER_ID,
    CL.CLAIM_DATE,
    CL.CLAIM_TYPE,
    CL.CLAIM_STATUS,
    CL.CLAIM_AMOUNT,
    CL.APPROVED_AMOUNT,

    P.POLICY_TYPE,
    P.POLICY_STATUS,
    P.COVERAGE_AMOUNT,
    P.PREMIUM_AMOUNT,

    C.FIRST_NAME,
    C.LAST_NAME,
    C.CUSTOMER_TYPE,

    CASE
        WHEN CL.CLAIM_ID IS NULL THEN 'CLAIM_NOT_FOUND'
        WHEN P.POLICY_ID IS NULL THEN 'POLICY_NOT_FOUND'
        WHEN PM.POLICY_ID <> CL.POLICY_ID
            THEN 'PAYMENT_POLICY_MISMATCH'
        ELSE 'MATCHED'
    END AS PAYMENT_RELATIONSHIP_STATUS,

    PM.CREATED_AT,
    PM.UPDATED_AT,
    PM.RAW_PAYLOAD,
    PM.SOURCE_FILE,
    PM.FILE_ROW_NUMBER,
    PM.LOAD_BATCH_ID,
    PM.SOURCE_SYSTEM,
    PM.RECORD_HASH

FROM {{ ref('stg_payment') }} PM

LEFT JOIN {{ ref('stg_claim') }} CL
    ON PM.CLAIM_ID = CL.CLAIM_ID

LEFT JOIN {{ ref('stg_policy') }} P
    ON PM.POLICY_ID = P.POLICY_ID

LEFT JOIN {{ ref('stg_customer') }} C
    ON CL.CUSTOMER_ID = C.CUSTOMER_ID

