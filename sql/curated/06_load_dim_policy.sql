USE DATABASE INSURANCE_DB;
USE SCHEMA CURATED;

SET RUN_TS = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

-- Prepare one valid source record per policy.
CREATE OR REPLACE TEMPORARY TABLE TMP_POLICY_SOURCE AS
SELECT
    P.POLICY_ID,
    P.CUSTOMER_ID,
    P.AGENT_ID,

    C.CUSTOMER_SK,
    A.AGENT_SK,

    P.POLICY_TYPE,
    P.POLICY_STATUS,
    P.POLICY_START_DATE,
    P.POLICY_END_DATE,
    P.PREMIUM_AMOUNT,
    P.COVERAGE_AMOUNT,

    P.CREATED_AT AS SOURCE_CREATED_AT,
    P.UPDATED_AT AS SOURCE_UPDATED_AT,

    P.SOURCE_FILE,
    P.FILE_ROW_NUMBER,
    P.LOAD_TIMESTAMP,
    P.LOAD_BATCH_ID,
    P.SOURCE_SYSTEM,
    P.RECORD_HASH,

    SHA2(
        TO_JSON(
            OBJECT_CONSTRUCT_KEEP_NULL(
                'CUSTOMER_ID', P.CUSTOMER_ID,
                'AGENT_ID', P.AGENT_ID,
                'POLICY_TYPE', P.POLICY_TYPE,
                'POLICY_STATUS', P.POLICY_STATUS,
                'POLICY_START_DATE', P.POLICY_START_DATE,
                'POLICY_END_DATE', P.POLICY_END_DATE,
                'PREMIUM_AMOUNT', P.PREMIUM_AMOUNT,
                'COVERAGE_AMOUNT', P.COVERAGE_AMOUNT
            )
        ),
        256
    ) AS ATTRIBUTE_HASH

FROM INSURANCE_DB.STAGING.POLICY_STAGING P

INNER JOIN INSURANCE_DB.CURATED.DIM_CUSTOMER C
    ON P.CUSTOMER_ID = C.CUSTOMER_ID
   AND C.IS_CURRENT = TRUE

INNER JOIN INSURANCE_DB.CURATED.DIM_AGENT A
    ON P.AGENT_ID = A.AGENT_ID

WHERE P.STAGING_STATUS = 'VALID'

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY P.POLICY_ID
    ORDER BY P.UPDATED_AT DESC NULLS LAST,
             P.LOAD_TIMESTAMP DESC NULLS LAST,
             P.FILE_ROW_NUMBER DESC
) = 1;


BEGIN TRANSACTION;

-- Step 1: Expire existing policy versions when attributes change.
UPDATE INSURANCE_DB.CURATED.DIM_POLICY T
SET
    EFFECTIVE_TO = $RUN_TS,
    IS_CURRENT = FALSE,
    UPDATED_AT = $RUN_TS
FROM TMP_POLICY_SOURCE S
WHERE T.POLICY_ID = S.POLICY_ID
  AND T.IS_CURRENT = TRUE
  AND NVL(T.ATTRIBUTE_HASH, '') <> S.ATTRIBUTE_HASH;


-- Step 2: Insert new policies and changed versions.
INSERT INTO INSURANCE_DB.CURATED.DIM_POLICY (
    POLICY_ID,
    CUSTOMER_SK,
    AGENT_SK,
    CUSTOMER_ID,
    AGENT_ID,
    POLICY_TYPE,
    POLICY_STATUS,
    POLICY_START_DATE,
    POLICY_END_DATE,
    PREMIUM_AMOUNT,
    COVERAGE_AMOUNT,
    SOURCE_CREATED_AT,
    SOURCE_UPDATED_AT,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT,
    ATTRIBUTE_HASH,
    RECORD_HASH,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    CREATED_AT,
    UPDATED_AT
)
SELECT
    S.POLICY_ID,
    S.CUSTOMER_SK,
    S.AGENT_SK,
    S.CUSTOMER_ID,
    S.AGENT_ID,
    S.POLICY_TYPE,
    S.POLICY_STATUS,
    S.POLICY_START_DATE,
    S.POLICY_END_DATE,
    S.PREMIUM_AMOUNT,
    S.COVERAGE_AMOUNT,
    S.SOURCE_CREATED_AT,
    S.SOURCE_UPDATED_AT,
    $RUN_TS,
    '9999-12-31 00:00:00'::TIMESTAMP_NTZ,
    TRUE,
    S.ATTRIBUTE_HASH,
    S.RECORD_HASH,
    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.LOAD_BATCH_ID,
    S.SOURCE_SYSTEM,
    $RUN_TS,
    $RUN_TS

FROM TMP_POLICY_SOURCE S
WHERE NOT EXISTS (
    SELECT 1
    FROM INSURANCE_DB.CURATED.DIM_POLICY T
    WHERE T.POLICY_ID = S.POLICY_ID
      AND T.IS_CURRENT = TRUE
);

COMMIT;
