USE DATABASE INSURANCE_DB;
USE SCHEMA CURATED;

MERGE INTO INSURANCE_DB.CURATED.DIM_AGENT T
USING (
    SELECT
        AGENT_ID,
        AGENT_NAME,
        AGENT_EMAIL,
        BRANCH,
        REGION,
        AGENT_STATUS,
        CREATED_AT AS SOURCE_CREATED_AT,
        UPDATED_AT AS SOURCE_UPDATED_AT,
        SOURCE_FILE,
        FILE_ROW_NUMBER,
        LOAD_BATCH_ID,
        SOURCE_SYSTEM,
        RECORD_HASH

    FROM INSURANCE_DB.STAGING.AGENT_STAGING
    WHERE STAGING_STATUS = 'VALID'

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY AGENT_ID
        ORDER BY UPDATED_AT DESC NULLS LAST,
                 LOAD_TIMESTAMP DESC NULLS LAST,
                 FILE_ROW_NUMBER DESC
    ) = 1
) S

ON T.AGENT_ID = S.AGENT_ID

WHEN MATCHED THEN UPDATE SET
    T.AGENT_NAME = S.AGENT_NAME,
    T.AGENT_EMAIL = S.AGENT_EMAIL,
    T.BRANCH = S.BRANCH,
    T.REGION = S.REGION,
    T.AGENT_STATUS = S.AGENT_STATUS,
    T.SOURCE_CREATED_AT = S.SOURCE_CREATED_AT,
    T.SOURCE_UPDATED_AT = S.SOURCE_UPDATED_AT,
    T.SOURCE_FILE = S.SOURCE_FILE,
    T.FILE_ROW_NUMBER = S.FILE_ROW_NUMBER,
    T.LOAD_BATCH_ID = S.LOAD_BATCH_ID,
    T.SOURCE_SYSTEM = S.SOURCE_SYSTEM,
    T.RECORD_HASH = S.RECORD_HASH,
    T.UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN INSERT (
    AGENT_ID,
    AGENT_NAME,
    AGENT_EMAIL,
    BRANCH,
    REGION,
    AGENT_STATUS,
    SOURCE_CREATED_AT,
    SOURCE_UPDATED_AT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    RECORD_HASH,
    CREATED_AT,
    UPDATED_AT
)
VALUES (
    S.AGENT_ID,
    S.AGENT_NAME,
    S.AGENT_EMAIL,
    S.BRANCH,
    S.REGION,
    S.AGENT_STATUS,
    S.SOURCE_CREATED_AT,
    S.SOURCE_UPDATED_AT,
    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.LOAD_BATCH_ID,
    S.SOURCE_SYSTEM,
    S.RECORD_HASH,
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP()
);
