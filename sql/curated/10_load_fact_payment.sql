USE DATABASE INSURANCE_DB;
USE SCHEMA CURATED;

SET RUN_TS = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;


-- Step 1: Select the latest valid payment record
CREATE OR REPLACE TEMP TABLE TMP_PAYMENT_SOURCE AS
SELECT
    PAYMENT_ID,
    CLAIM_ID,
    POLICY_ID,
    PAYMENT_AMOUNT,
    PAYMENT_DATE,
    PAYMENT_METHOD,
    PAYMENT_STATUS,
    CREATED_AT AS SOURCE_CREATED_AT,
    UPDATED_AT AS SOURCE_UPDATED_AT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    RECORD_HASH

FROM INSURANCE_DB.STAGING.PAYMENT_STAGING

WHERE UPPER(STAGING_STATUS) = 'VALID'

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY PAYMENT_ID
    ORDER BY
        UPDATED_AT DESC NULLS LAST,
        LOAD_TIMESTAMP DESC NULLS LAST,
        FILE_ROW_NUMBER DESC
) = 1;


-- Step 2: Resolve fact and dimension surrogate keys
CREATE OR REPLACE TEMP TABLE TMP_FACT_PAYMENT_SOURCE AS
SELECT
    P.PAYMENT_ID,
    P.CLAIM_ID,
    P.POLICY_ID,

    C.CLAIM_SK,
    C.POLICY_SK,
    C.CUSTOMER_SK,
    C.AGENT_SK,

    P.PAYMENT_AMOUNT,
    P.PAYMENT_DATE,
    P.PAYMENT_METHOD,
    P.PAYMENT_STATUS,

    P.SOURCE_CREATED_AT,
    P.SOURCE_UPDATED_AT,

    P.SOURCE_FILE,
    P.FILE_ROW_NUMBER,
    P.LOAD_BATCH_ID,
    P.SOURCE_SYSTEM,
    P.RECORD_HASH

FROM TMP_PAYMENT_SOURCE P

INNER JOIN INSURANCE_DB.CURATED.FACT_CLAIM C
    ON P.CLAIM_ID = C.CLAIM_ID
   AND P.POLICY_ID = C.POLICY_ID;


-- Step 3: Merge into FACT_PAYMENT
MERGE INTO INSURANCE_DB.CURATED.FACT_PAYMENT T
USING TMP_FACT_PAYMENT_SOURCE S
    ON T.PAYMENT_ID = S.PAYMENT_ID

WHEN MATCHED THEN UPDATE SET
    T.CLAIM_ID            = S.CLAIM_ID,
    T.POLICY_ID           = S.POLICY_ID,
    T.CLAIM_SK            = S.CLAIM_SK,
    T.POLICY_SK           = S.POLICY_SK,
    T.CUSTOMER_SK         = S.CUSTOMER_SK,
    T.AGENT_SK            = S.AGENT_SK,
    T.PAYMENT_AMOUNT      = S.PAYMENT_AMOUNT,
    T.PAYMENT_DATE        = S.PAYMENT_DATE,
    T.PAYMENT_METHOD      = S.PAYMENT_METHOD,
    T.PAYMENT_STATUS      = S.PAYMENT_STATUS,
    T.SOURCE_CREATED_AT   = S.SOURCE_CREATED_AT,
    T.SOURCE_UPDATED_AT   = S.SOURCE_UPDATED_AT,
    T.SOURCE_FILE         = S.SOURCE_FILE,
    T.FILE_ROW_NUMBER     = S.FILE_ROW_NUMBER,
    T.LOAD_BATCH_ID       = S.LOAD_BATCH_ID,
    T.SOURCE_SYSTEM       = S.SOURCE_SYSTEM,
    T.RECORD_HASH         = S.RECORD_HASH,
    T.UPDATED_AT          = $RUN_TS

WHEN NOT MATCHED THEN INSERT (
    PAYMENT_ID,
    CLAIM_ID,
    POLICY_ID,
    CLAIM_SK,
    POLICY_SK,
    CUSTOMER_SK,
    AGENT_SK,
    PAYMENT_AMOUNT,
    PAYMENT_DATE,
    PAYMENT_METHOD,
    PAYMENT_STATUS,
    SOURCE_CREATED_AT,
    SOURCE_UPDATED_AT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    RECORD_HASH,
    CREATED_AT,
    UPDATED_AT
)
VALUES (
    S.PAYMENT_ID,
    S.CLAIM_ID,
    S.POLICY_ID,
    S.CLAIM_SK,
    S.POLICY_SK,
    S.CUSTOMER_SK,
    S.AGENT_SK,
    S.PAYMENT_AMOUNT,
    S.PAYMENT_DATE,
    S.PAYMENT_METHOD,
    S.PAYMENT_STATUS,
    S.SOURCE_CREATED_AT,
    S.SOURCE_UPDATED_AT,
    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.LOAD_BATCH_ID,
    S.SOURCE_SYSTEM,
    S.RECORD_HASH,
    $RUN_TS,
    $RUN_TS
);
