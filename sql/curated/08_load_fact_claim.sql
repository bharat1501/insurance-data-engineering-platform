USE DATABASE INSURANCE_DB;
USE SCHEMA CURATED;

-- Capture one consistent timestamp for this load
SET RUN_TS = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

-- Prepare the latest valid staging record for each claim
CREATE OR REPLACE TEMP TABLE TMP_CLAIM_SOURCE AS
SELECT
    C.CLAIM_ID,
    C.POLICY_ID,
    C.CUSTOMER_ID,

    C.CLAIM_DATE,
    C.INCIDENT_DATE,
    C.CLAIM_TYPE,
    C.CLAIM_STATUS,
    C.CLAIM_AMOUNT,
    C.APPROVED_AMOUNT,
    C.SETTLEMENT_DATE,

    C.CREATED_AT AS SOURCE_CREATED_AT,
    C.UPDATED_AT AS SOURCE_UPDATED_AT,

    C.SOURCE_FILE,
    C.FILE_ROW_NUMBER,
    C.LOAD_BATCH_ID,
    C.SOURCE_SYSTEM,
    C.RECORD_HASH

FROM INSURANCE_DB.STAGING.CLAIM_STAGING C

WHERE UPPER(C.STAGING_STATUS) = 'VALID'

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY C.CLAIM_ID
    ORDER BY
        C.UPDATED_AT DESC NULLS LAST,
        C.LOAD_TIMESTAMP DESC NULLS LAST,
        C.FILE_ROW_NUMBER DESC
) = 1;


-- Resolve dimension surrogate keys
CREATE OR REPLACE TEMP TABLE TMP_FACT_CLAIM_SOURCE AS
SELECT
    C.CLAIM_ID,

    P.POLICY_SK,
    D.CUSTOMER_SK,
    P.AGENT_SK,

    C.POLICY_ID,
    C.CUSTOMER_ID,

    C.CLAIM_DATE,
    C.INCIDENT_DATE,
    C.CLAIM_TYPE,
    C.CLAIM_STATUS,
    C.CLAIM_AMOUNT,
    C.APPROVED_AMOUNT,
    C.SETTLEMENT_DATE,

    C.SOURCE_CREATED_AT,
    C.SOURCE_UPDATED_AT,

    C.SOURCE_FILE,
    C.FILE_ROW_NUMBER,
    C.LOAD_BATCH_ID,
    C.SOURCE_SYSTEM,
    C.RECORD_HASH

FROM TMP_CLAIM_SOURCE C

INNER JOIN INSURANCE_DB.CURATED.DIM_POLICY P
    ON C.POLICY_ID = P.POLICY_ID
   AND P.IS_CURRENT = TRUE

INNER JOIN INSURANCE_DB.CURATED.DIM_CUSTOMER D
    ON C.CUSTOMER_ID = D.CUSTOMER_ID
   AND D.IS_CURRENT = TRUE

WHERE P.CUSTOMER_ID = C.CUSTOMER_ID;


-- Load the fact table
MERGE INTO INSURANCE_DB.CURATED.FACT_CLAIM T
USING TMP_FACT_CLAIM_SOURCE S
    ON T.CLAIM_ID = S.CLAIM_ID

WHEN MATCHED THEN UPDATE SET
    T.POLICY_SK          = S.POLICY_SK,
    T.CUSTOMER_SK        = S.CUSTOMER_SK,
    T.AGENT_SK           = S.AGENT_SK,
    T.POLICY_ID          = S.POLICY_ID,
    T.CUSTOMER_ID        = S.CUSTOMER_ID,
    T.CLAIM_DATE         = S.CLAIM_DATE,
    T.INCIDENT_DATE      = S.INCIDENT_DATE,
    T.CLAIM_TYPE         = S.CLAIM_TYPE,
    T.CLAIM_STATUS       = S.CLAIM_STATUS,
    T.CLAIM_AMOUNT       = S.CLAIM_AMOUNT,
    T.APPROVED_AMOUNT    = S.APPROVED_AMOUNT,
    T.SETTLEMENT_DATE    = S.SETTLEMENT_DATE,
    T.SOURCE_CREATED_AT  = S.SOURCE_CREATED_AT,
    T.SOURCE_UPDATED_AT  = S.SOURCE_UPDATED_AT,
    T.SOURCE_FILE        = S.SOURCE_FILE,
    T.FILE_ROW_NUMBER    = S.FILE_ROW_NUMBER,
    T.LOAD_BATCH_ID      = S.LOAD_BATCH_ID,
    T.SOURCE_SYSTEM      = S.SOURCE_SYSTEM,
    T.RECORD_HASH        = S.RECORD_HASH,
    T.UPDATED_AT         = $RUN_TS

WHEN NOT MATCHED THEN INSERT (
    CLAIM_ID,
    POLICY_SK,
    CUSTOMER_SK,
    AGENT_SK,
    POLICY_ID,
    CUSTOMER_ID,
    CLAIM_DATE,
    INCIDENT_DATE,
    CLAIM_TYPE,
    CLAIM_STATUS,
    CLAIM_AMOUNT,
    APPROVED_AMOUNT,
    SETTLEMENT_DATE,
    SOURCE_CREATED_AT,
    SOURCE_UPDATED_AT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    RECORD_HASH,
    CREATED_AT,
    UPDATED_AT
)
VALUES (
    S.CLAIM_ID,
    S.POLICY_SK,
    S.CUSTOMER_SK,
    S.AGENT_SK,
    S.POLICY_ID,
    S.CUSTOMER_ID,
    S.CLAIM_DATE,
    S.INCIDENT_DATE,
    S.CLAIM_TYPE,
    S.CLAIM_STATUS,
    S.CLAIM_AMOUNT,
    S.APPROVED_AMOUNT,
    S.SETTLEMENT_DATE,
    S.SOURCE_CREATED_AT,
    S.SOURCE_UPDATED_AT,
    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.LOAD_BATCH_ID,
    S.SOURCE_SYSTEM,
    S.RECORD_HASH,
    $RUN_TS,
    $RUN_TS
);
