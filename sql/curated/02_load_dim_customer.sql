USE DATABASE INSURANCE_DB;
USE SCHEMA CURATED;

SET RUN_TS = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ;

-- Prepare one valid source record per customer.
CREATE OR REPLACE TEMPORARY TABLE TMP_CUSTOMER_SOURCE AS
SELECT
    CUSTOMER_ID,
    FIRST_NAME,
    LAST_NAME,
    DATE_OF_BIRTH,
    EMAIL,
    PHONE,
    ADDRESS,
    CITY,
    STATE,
    CUSTOMER_TYPE,

    CREATED_AT AS SOURCE_CREATED_AT,
    UPDATED_AT AS SOURCE_UPDATED_AT,

    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_TIMESTAMP,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    RECORD_HASH,

    SHA2(
        TO_JSON(
            OBJECT_CONSTRUCT_KEEP_NULL(
                'FIRST_NAME', FIRST_NAME,
                'LAST_NAME', LAST_NAME,
                'DATE_OF_BIRTH', DATE_OF_BIRTH,
                'EMAIL', EMAIL,
                'PHONE', PHONE,
                'ADDRESS', ADDRESS,
                'CITY', CITY,
                'STATE', STATE,
                'CUSTOMER_TYPE', CUSTOMER_TYPE
            )
        ),
        256
    ) AS ATTRIBUTE_HASH

FROM INSURANCE_DB.STAGING.CUSTOMER_STAGING
WHERE STAGING_STATUS = 'VALID'

QUALIFY ROW_NUMBER() OVER (
    PARTITION BY CUSTOMER_ID
    ORDER BY UPDATED_AT DESC NULLS LAST,
             LOAD_TIMESTAMP DESC NULLS LAST,
             FILE_ROW_NUMBER DESC
) = 1;


BEGIN TRANSACTION;

-- Expire current versions when customer attributes change.
UPDATE INSURANCE_DB.CURATED.DIM_CUSTOMER T
SET
    EFFECTIVE_TO = $RUN_TS,
    IS_CURRENT = FALSE,
    UPDATED_AT = $RUN_TS
FROM TMP_CUSTOMER_SOURCE S
WHERE T.CUSTOMER_ID = S.CUSTOMER_ID
  AND T.IS_CURRENT = TRUE
  AND NVL(T.ATTRIBUTE_HASH, '') <> S.ATTRIBUTE_HASH;


-- Insert new customers and changed customer versions.
INSERT INTO INSURANCE_DB.CURATED.DIM_CUSTOMER (
    CUSTOMER_ID,
    FIRST_NAME,
    LAST_NAME,
    DATE_OF_BIRTH,
    EMAIL,
    PHONE,
    ADDRESS,
    CITY,
    STATE,
    CUSTOMER_TYPE,
    EFFECTIVE_FROM,
    EFFECTIVE_TO,
    IS_CURRENT,
    ATTRIBUTE_HASH,
    RECORD_HASH,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    CREATED_AT,
    UPDATED_AT
)
SELECT
    S.CUSTOMER_ID,
    S.FIRST_NAME,
    S.LAST_NAME,
    S.DATE_OF_BIRTH,
    S.EMAIL,
    S.PHONE,
    S.ADDRESS,
    S.CITY,
    S.STATE,
    S.CUSTOMER_TYPE,

    $RUN_TS,
    '9999-12-31 00:00:00'::TIMESTAMP_NTZ,
    TRUE,

    S.ATTRIBUTE_HASH,
    S.RECORD_HASH,

    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.LOAD_BATCH_ID,
    S.SOURCE_SYSTEM,

    $RUN_TS,
    $RUN_TS

FROM TMP_CUSTOMER_SOURCE S
WHERE NOT EXISTS (
    SELECT 1
    FROM INSURANCE_DB.CURATED.DIM_CUSTOMER T
    WHERE T.CUSTOMER_ID = S.CUSTOMER_ID
      AND T.IS_CURRENT = TRUE
);

COMMIT;
