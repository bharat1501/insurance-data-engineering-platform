USE DATABASE INSURANCE_DB;
USE SCHEMA CURATED;

CREATE TABLE IF NOT EXISTS FACT_CLAIM (
    CLAIM_SK              NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    CLAIM_ID              VARCHAR NOT NULL,

    POLICY_SK             NUMBER(38,0),
    CUSTOMER_SK           NUMBER(38,0),
    AGENT_SK              NUMBER(38,0),

    POLICY_ID             VARCHAR,
    CUSTOMER_ID           VARCHAR,

    CLAIM_DATE            DATE,
    INCIDENT_DATE         DATE,
    CLAIM_TYPE            VARCHAR,
    CLAIM_STATUS          VARCHAR,
    CLAIM_AMOUNT          NUMBER(12,2),
    APPROVED_AMOUNT       NUMBER(12,2),
    SETTLEMENT_DATE       DATE,

    SOURCE_CREATED_AT     TIMESTAMP_NTZ,
    SOURCE_UPDATED_AT     TIMESTAMP_NTZ,

    SOURCE_FILE           VARCHAR,
    FILE_ROW_NUMBER       NUMBER(38,0),
    LOAD_BATCH_ID         VARCHAR,
    SOURCE_SYSTEM         VARCHAR,
    RECORD_HASH           VARCHAR,

    CREATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT            TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
