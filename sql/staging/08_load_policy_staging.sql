USE DATABASE INSURANCE_DB;
USE SCHEMA STAGING;

SET BATCH_ID = 'BATCH_20261003_001';

MERGE INTO POLICY_STAGING T
USING (
    SELECT
        R.POLICY_ID,
        R.CUSTOMER_ID,
        R.POLICY_TYPE,
        R.POLICY_STATUS,
        TRY_TO_DATE(R.POLICY_START_DATE) AS POLICY_START_DATE,
        TRY_TO_DATE(R.POLICY_END_DATE) AS POLICY_END_DATE,
        TRY_TO_DECIMAL(R.PREMIUM_AMOUNT, 18, 2) AS PREMIUM_AMOUNT,
        TRY_TO_DECIMAL(R.COVERAGE_AMOUNT, 18, 2) AS COVERAGE_AMOUNT,
        R.AGENT_ID,
        TRY_TO_TIMESTAMP_NTZ(R.CREATED_AT) AS CREATED_AT,
        TRY_TO_TIMESTAMP_NTZ(R.UPDATED_AT) AS UPDATED_AT,
        R.SOURCE_FILE,
        R.FILE_ROW_NUMBER,
        R.LOAD_TIMESTAMP,
        R.LOAD_BATCH_ID,
        R.SOURCE_SYSTEM,
        R.RECORD_HASH,

        CASE
            WHEN R.POLICY_ID IS NULL OR TRIM(R.POLICY_ID) = ''
                THEN 'MISSING POLICY_ID'

            WHEN R.CUSTOMER_ID IS NULL OR TRIM(R.CUSTOMER_ID) = ''
                THEN 'MISSING CUSTOMER_ID'

            WHEN R.AGENT_ID IS NULL OR TRIM(R.AGENT_ID) = ''
                THEN 'MISSING AGENT_ID'

            WHEN R.POLICY_TYPE IS NULL OR TRIM(R.POLICY_TYPE) = ''
                THEN 'MISSING POLICY_TYPE'

            WHEN R.POLICY_STATUS IS NULL OR TRIM(R.POLICY_STATUS) = ''
                THEN 'MISSING POLICY_STATUS'

            WHEN R.POLICY_START_DATE IS NULL
                 OR TRIM(R.POLICY_START_DATE) = ''
                THEN 'MISSING POLICY_START_DATE'

            WHEN TRY_TO_DATE(R.POLICY_START_DATE) IS NULL
                THEN 'INVALID POLICY_START_DATE'

            WHEN R.POLICY_END_DATE IS NOT NULL
                 AND TRIM(R.POLICY_END_DATE) <> ''
                 AND TRY_TO_DATE(R.POLICY_END_DATE) IS NULL
                THEN 'INVALID POLICY_END_DATE'

            WHEN TRY_TO_DATE(R.POLICY_END_DATE) IS NOT NULL
                 AND TRY_TO_DATE(R.POLICY_START_DATE)
                     > TRY_TO_DATE(R.POLICY_END_DATE)
                THEN 'POLICY_START_DATE AFTER POLICY_END_DATE'

            WHEN R.PREMIUM_AMOUNT IS NULL
                 OR TRIM(R.PREMIUM_AMOUNT) = ''
                THEN 'MISSING PREMIUM_AMOUNT'

            WHEN TRY_TO_DECIMAL(R.PREMIUM_AMOUNT, 18, 2) IS NULL
                THEN 'INVALID PREMIUM_AMOUNT'

            WHEN R.COVERAGE_AMOUNT IS NULL
                 OR TRIM(R.COVERAGE_AMOUNT) = ''
                THEN 'MISSING COVERAGE_AMOUNT'

            WHEN TRY_TO_DECIMAL(R.COVERAGE_AMOUNT, 18, 2) IS NULL
                THEN 'INVALID COVERAGE_AMOUNT'

            WHEN NOT EXISTS (
                SELECT 1
                FROM INSURANCE_DB.STAGING.CUSTOMER_STAGING C
                WHERE C.CUSTOMER_ID = R.CUSTOMER_ID
                  AND C.STAGING_STATUS = 'VALID'
            )
                THEN 'CUSTOMER NOT FOUND IN VALID STAGING'

            WHEN NOT EXISTS (
                SELECT 1
                FROM INSURANCE_DB.STAGING.AGENT_STAGING A
                WHERE A.AGENT_ID = R.AGENT_ID
                  AND A.STAGING_STATUS = 'VALID'
            )
                THEN 'AGENT NOT FOUND IN VALID STAGING'

            ELSE NULL
        END AS VALIDATION_REASON

    FROM INSURANCE_DB.RAW.POLICY_RAW R
    WHERE R.LOAD_BATCH_ID = $BATCH_ID
) S

ON  T.LOAD_BATCH_ID = S.LOAD_BATCH_ID
AND T.SOURCE_FILE = S.SOURCE_FILE
AND T.FILE_ROW_NUMBER = S.FILE_ROW_NUMBER

WHEN MATCHED THEN UPDATE SET
    T.POLICY_ID = S.POLICY_ID,
    T.CUSTOMER_ID = S.CUSTOMER_ID,
    T.POLICY_TYPE = S.POLICY_TYPE,
    T.POLICY_STATUS = S.POLICY_STATUS,
    T.POLICY_START_DATE = S.POLICY_START_DATE,
    T.POLICY_END_DATE = S.POLICY_END_DATE,
    T.PREMIUM_AMOUNT = S.PREMIUM_AMOUNT,
    T.COVERAGE_AMOUNT = S.COVERAGE_AMOUNT,
    T.AGENT_ID = S.AGENT_ID,
    T.CREATED_AT = S.CREATED_AT,
    T.UPDATED_AT = S.UPDATED_AT,
    T.LOAD_TIMESTAMP = S.LOAD_TIMESTAMP,
    T.SOURCE_SYSTEM = S.SOURCE_SYSTEM,
    T.RECORD_HASH = S.RECORD_HASH,
    T.STAGING_STATUS =
        IFF(S.VALIDATION_REASON IS NULL, 'VALID', 'REJECTED'),
    T.VALIDATION_REASON = S.VALIDATION_REASON

WHEN NOT MATCHED THEN INSERT (
    POLICY_ID,
    CUSTOMER_ID,
    POLICY_TYPE,
    POLICY_STATUS,
    POLICY_START_DATE,
    POLICY_END_DATE,
    PREMIUM_AMOUNT,
    COVERAGE_AMOUNT,
    AGENT_ID,
    CREATED_AT,
    UPDATED_AT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_TIMESTAMP,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    RECORD_HASH,
    STAGING_STATUS,
    VALIDATION_REASON
)
VALUES (
    S.POLICY_ID,
    S.CUSTOMER_ID,
    S.POLICY_TYPE,
    S.POLICY_STATUS,
    S.POLICY_START_DATE,
    S.POLICY_END_DATE,
    S.PREMIUM_AMOUNT,
    S.COVERAGE_AMOUNT,
    S.AGENT_ID,
    S.CREATED_AT,
    S.UPDATED_AT,
    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.LOAD_TIMESTAMP,
    S.LOAD_BATCH_ID,
    S.SOURCE_SYSTEM,
    S.RECORD_HASH,
    IFF(S.VALIDATION_REASON IS NULL, 'VALID', 'REJECTED'),
    S.VALIDATION_REASON
);
