USE DATABASE INSURANCE_DB;
USE SCHEMA STAGING;

SET BATCH_ID = 'BATCH_20261003_001';

MERGE INTO AGENT_STAGING T
USING (
    SELECT
        AGENT_ID,
        AGENT_NAME,
        AGENT_EMAIL,
        BRANCH,
        REGION,
        AGENT_STATUS,
        TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,
        TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT,
        SOURCE_FILE,
        FILE_ROW_NUMBER,
        LOAD_TIMESTAMP,
        LOAD_BATCH_ID,
        SOURCE_SYSTEM,
        RECORD_HASH,

        CASE
            WHEN AGENT_ID IS NULL OR TRIM(AGENT_ID) = ''
                THEN 'MISSING AGENT_ID'
            WHEN AGENT_NAME IS NULL OR TRIM(AGENT_NAME) = ''
                THEN 'MISSING AGENT_NAME'
            WHEN AGENT_EMAIL IS NULL OR TRIM(AGENT_EMAIL) = ''
                THEN 'MISSING AGENT_EMAIL'
            WHEN BRANCH IS NULL OR TRIM(BRANCH) = ''
                THEN 'MISSING BRANCH'
            WHEN REGION IS NULL OR TRIM(REGION) = ''
                THEN 'MISSING REGION'
            WHEN AGENT_STATUS IS NULL OR TRIM(AGENT_STATUS) = ''
                THEN 'MISSING AGENT_STATUS'
            WHEN UPPER(TRIM(AGENT_STATUS)) NOT IN ('ACTIVE', 'INACTIVE')
                THEN 'INVALID AGENT_STATUS'
            WHEN CREATED_AT IS NOT NULL
                 AND TRIM(CREATED_AT) <> ''
                 AND TRY_TO_TIMESTAMP_NTZ(CREATED_AT) IS NULL
                THEN 'INVALID CREATED_AT'
            WHEN UPDATED_AT IS NOT NULL
                 AND TRIM(UPDATED_AT) <> ''
                 AND TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) IS NULL
                THEN 'INVALID UPDATED_AT'
            ELSE NULL
        END AS VALIDATION_REASON

    FROM INSURANCE_DB.RAW.AGENT_RAW
    WHERE LOAD_BATCH_ID = $BATCH_ID
) S

ON  T.LOAD_BATCH_ID = S.LOAD_BATCH_ID
AND T.SOURCE_FILE = S.SOURCE_FILE
AND T.FILE_ROW_NUMBER = S.FILE_ROW_NUMBER

WHEN MATCHED THEN UPDATE SET
    T.AGENT_ID = S.AGENT_ID,
    T.AGENT_NAME = S.AGENT_NAME,
    T.AGENT_EMAIL = S.AGENT_EMAIL,
    T.BRANCH = S.BRANCH,
    T.REGION = S.REGION,
    T.AGENT_STATUS = S.AGENT_STATUS,
    T.CREATED_AT = S.CREATED_AT,
    T.UPDATED_AT = S.UPDATED_AT,
    T.LOAD_TIMESTAMP = S.LOAD_TIMESTAMP,
    T.SOURCE_SYSTEM = S.SOURCE_SYSTEM,
    T.RECORD_HASH = S.RECORD_HASH,
    T.STAGING_STATUS =
        IFF(S.VALIDATION_REASON IS NULL, 'VALID', 'REJECTED'),
    T.VALIDATION_REASON = S.VALIDATION_REASON

WHEN NOT MATCHED THEN INSERT (
    AGENT_ID,
    AGENT_NAME,
    AGENT_EMAIL,
    BRANCH,
    REGION,
    AGENT_STATUS,
    CREATED_AT,
    UPDATED_AT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_TIMESTAMP,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    RECORD_HASH,
    STAGING_STATUS,
    VALIDATION_REASON
)
VALUES (
    S.AGENT_ID,
    S.AGENT_NAME,
    S.AGENT_EMAIL,
    S.BRANCH,
    S.REGION,
    S.AGENT_STATUS,
    S.CREATED_AT,
    S.UPDATED_AT,
    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.LOAD_TIMESTAMP,
    S.LOAD_BATCH_ID,
    S.SOURCE_SYSTEM,
    S.RECORD_HASH,
    IFF(S.VALIDATION_REASON IS NULL, 'VALID', 'REJECTED'),
    S.VALIDATION_REASON
);
