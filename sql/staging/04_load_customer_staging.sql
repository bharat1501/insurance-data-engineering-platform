USE DATABASE INSURANCE_DB;
USE SCHEMA STAGING;

SET BATCH_ID = 'BATCH_20261003_001';

MERGE INTO CUSTOMER_STAGING T
USING (
    SELECT
        CUSTOMER_ID,
        FIRST_NAME,
        LAST_NAME,
        TRY_TO_DATE(DATE_OF_BIRTH) AS DATE_OF_BIRTH,
        EMAIL,
        PHONE,
        ADDRESS,
        CITY,
        STATE,
        CUSTOMER_TYPE,
        TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,
        TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT,
        SOURCE_FILE,
        FILE_ROW_NUMBER,
        LOAD_TIMESTAMP,
        LOAD_BATCH_ID,
        SOURCE_SYSTEM,
        RECORD_HASH,

        CASE
            WHEN CUSTOMER_ID IS NULL OR TRIM(CUSTOMER_ID) = ''
                THEN 'MISSING CUSTOMER_ID'
            WHEN FIRST_NAME IS NULL OR TRIM(FIRST_NAME) = ''
                THEN 'MISSING FIRST_NAME'
            WHEN LAST_NAME IS NULL OR TRIM(LAST_NAME) = ''
                THEN 'MISSING LAST_NAME'
            WHEN EMAIL IS NULL OR TRIM(EMAIL) = ''
                THEN 'MISSING EMAIL'
            WHEN DATE_OF_BIRTH IS NOT NULL
                 AND TRIM(DATE_OF_BIRTH) <> ''
                 AND TRY_TO_DATE(DATE_OF_BIRTH) IS NULL
                THEN 'INVALID DATE_OF_BIRTH'
            WHEN CUSTOMER_TYPE IS NULL OR TRIM(CUSTOMER_TYPE) = ''
                THEN 'MISSING CUSTOMER_TYPE'
            ELSE NULL
        END AS VALIDATION_REASON

    FROM INSURANCE_DB.RAW.CUSTOMER_RAW
    WHERE LOAD_BATCH_ID = $BATCH_ID
) S

ON  T.LOAD_BATCH_ID = S.LOAD_BATCH_ID
AND T.SOURCE_FILE = S.SOURCE_FILE
AND T.FILE_ROW_NUMBER = S.FILE_ROW_NUMBER

WHEN MATCHED THEN UPDATE SET
    T.CUSTOMER_ID = S.CUSTOMER_ID,
    T.FIRST_NAME = S.FIRST_NAME,
    T.LAST_NAME = S.LAST_NAME,
    T.DATE_OF_BIRTH = S.DATE_OF_BIRTH,
    T.EMAIL = S.EMAIL,
    T.PHONE = S.PHONE,
    T.ADDRESS = S.ADDRESS,
    T.CITY = S.CITY,
    T.STATE = S.STATE,
    T.CUSTOMER_TYPE = S.CUSTOMER_TYPE,
    T.CREATED_AT = S.CREATED_AT,
    T.UPDATED_AT = S.UPDATED_AT,
    T.LOAD_TIMESTAMP = S.LOAD_TIMESTAMP,
    T.SOURCE_SYSTEM = S.SOURCE_SYSTEM,
    T.RECORD_HASH = S.RECORD_HASH,
    T.STAGING_STATUS =
        IFF(S.VALIDATION_REASON IS NULL, 'VALID', 'REJECTED'),
    T.VALIDATION_REASON = S.VALIDATION_REASON

WHEN NOT MATCHED THEN INSERT (
    CUSTOMER_ID,
    FIRST_NAME,
    LAST_NAME,
    DATE_OF_BIRTH,
    EMAIL,
    PHONE,
    ADDRESS,
    CITY,
    STATE,
    CUSTOMER_TYPE,
    CREATED_AT,
    UPDATED_AT,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    LOAD_TIMESTAMP,
    LOAD_BATCH_ID,
    SOURCE_SYSTEM,
    RECORD_HASH,
    STAGING_STATUS,
    VALIDATION_REASON
)
VALUES (
    S.CUSTOMER_ID,
    S.FIRST_NAME,
    S.LAST_NAME,
    S.DATE_OF_BIRTH,
    S.EMAIL,
    S.PHONE,
    S.ADDRESS,
    S.CITY,
    S.STATE,
    S.CUSTOMER_TYPE,
    S.CREATED_AT,
    S.UPDATED_AT,
    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.LOAD_TIMESTAMP,
    S.LOAD_BATCH_ID,
    S.SOURCE_SYSTEM,
    S.RECORD_HASH,
    IFF(S.VALIDATION_REASON IS NULL, 'VALID', 'REJECTED'),
    S.VALIDATION_REASON
);
