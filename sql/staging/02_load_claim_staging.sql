
-- Idempotent claims staging load.
SET BATCH_ID = 'BATCH_20261028_RECOVERY_009';

MERGE INTO INSURANCE_DB.STAGING.CLAIM_STAGING AS T
USING (
    SELECT
        CLAIM_ID,
        POLICY_ID,
        CUSTOMER_ID,
        TRY_TO_DATE(CLAIM_DATE) AS CLAIM_DATE,
        TRY_TO_DATE(INCIDENT_DATE) AS INCIDENT_DATE,
        CLAIM_TYPE,
        CLAIM_STATUS,
        TRY_TO_DECIMAL(CLAIM_AMOUNT, 12, 2) AS CLAIM_AMOUNT,
        TRY_TO_DECIMAL(APPROVED_AMOUNT, 12, 2) AS APPROVED_AMOUNT,
        TRY_TO_DATE(SETTLEMENT_DATE) AS SETTLEMENT_DATE,
        TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,
        TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT,
        SOURCE_FILE,
        FILE_ROW_NUMBER,
        LOAD_TIMESTAMP,
        LOAD_BATCH_ID,
        SOURCE_SYSTEM,
        RECORD_HASH,
        CASE
            WHEN CLAIM_ID IS NULL OR TRIM(CLAIM_ID) = ''
                THEN 'MISSING_CLAIM_ID'
            WHEN CLAIM_AMOUNT IS NULL OR TRIM(CLAIM_AMOUNT) = ''
                THEN 'MISSING_CLAIM_AMOUNT'
            WHEN TRY_TO_DECIMAL(CLAIM_AMOUNT, 12, 2) IS NULL
                THEN 'INVALID_CLAIM_AMOUNT'
            WHEN TRY_TO_DATE(CLAIM_DATE) IS NULL
                THEN 'INVALID_CLAIM_DATE'
            WHEN CLAIM_STATUS IS NULL OR CLAIM_STATUS NOT IN (
               'OPEN', 'SUBMITTED', 'UNDER_REVIEW', 'APPROVED',
                'REJECTED', 'SETTLED'
            )
                THEN 'INVALID_CLAIM_STATUS'
            ELSE NULL
        END AS VALIDATION_REASON
    FROM INSURANCE_DB.RAW.CLAIM_RAW
    WHERE LOAD_BATCH_ID = $BATCH_ID
) AS S
ON  T.LOAD_BATCH_ID = S.LOAD_BATCH_ID
AND T.SOURCE_FILE = S.SOURCE_FILE
AND T.FILE_ROW_NUMBER = S.FILE_ROW_NUMBER

WHEN MATCHED THEN UPDATE SET
    T.CLAIM_ID = S.CLAIM_ID,
    T.POLICY_ID = S.POLICY_ID,
    T.CUSTOMER_ID = S.CUSTOMER_ID,
    T.CLAIM_DATE = S.CLAIM_DATE,
    T.INCIDENT_DATE = S.INCIDENT_DATE,
    T.CLAIM_TYPE = S.CLAIM_TYPE,
    T.CLAIM_STATUS = S.CLAIM_STATUS,
    T.CLAIM_AMOUNT = S.CLAIM_AMOUNT,
    T.APPROVED_AMOUNT = S.APPROVED_AMOUNT,
    T.SETTLEMENT_DATE = S.SETTLEMENT_DATE,
    T.CREATED_AT = S.CREATED_AT,
    T.UPDATED_AT = S.UPDATED_AT,
    T.LOAD_TIMESTAMP = S.LOAD_TIMESTAMP,
    T.SOURCE_SYSTEM = S.SOURCE_SYSTEM,
    T.RECORD_HASH = S.RECORD_HASH,
    T.STAGING_STATUS = IFF(
        S.VALIDATION_REASON IS NULL, 'VALID', 'REJECTED'
    ),
    T.VALIDATION_REASON = S.VALIDATION_REASON

WHEN NOT MATCHED THEN INSERT (
    CLAIM_ID, POLICY_ID, CUSTOMER_ID,
    CLAIM_DATE, INCIDENT_DATE, CLAIM_TYPE, CLAIM_STATUS,
    CLAIM_AMOUNT, APPROVED_AMOUNT, SETTLEMENT_DATE,
    CREATED_AT, UPDATED_AT, SOURCE_FILE, FILE_ROW_NUMBER,
    LOAD_TIMESTAMP, LOAD_BATCH_ID, SOURCE_SYSTEM, RECORD_HASH,
    STAGING_STATUS, VALIDATION_REASON
)
VALUES (
    S.CLAIM_ID, S.POLICY_ID, S.CUSTOMER_ID,
    S.CLAIM_DATE, S.INCIDENT_DATE, S.CLAIM_TYPE, S.CLAIM_STATUS,
    S.CLAIM_AMOUNT, S.APPROVED_AMOUNT, S.SETTLEMENT_DATE,
    S.CREATED_AT, S.UPDATED_AT, S.SOURCE_FILE, S.FILE_ROW_NUMBER,
    S.LOAD_TIMESTAMP, S.LOAD_BATCH_ID, S.SOURCE_SYSTEM, S.RECORD_HASH,
    IFF(S.VALIDATION_REASON IS NULL, 'VALID', 'REJECTED'),
    S.VALIDATION_REASON
);

