
-- Quarantine rejected claims for a specific batch.
-- Re-running this script does not insert duplicate rejection entries.

SET BATCH_ID = 'BATCH_20261009_BAD_001';

MERGE INTO INSURANCE_DB.AUDIT.REJECTED_RECORDS AS T
USING (
    SELECT
        'CLAIM' AS SOURCE_ENTITY,
        LOAD_BATCH_ID,
        SOURCE_FILE,
        FILE_ROW_NUMBER,
        CLAIM_ID AS RECORD_ID,
        VALIDATION_REASON AS REJECTION_REASON,
        OBJECT_CONSTRUCT_KEEP_NULL(
            'CLAIM_ID', CLAIM_ID,
            'POLICY_ID', POLICY_ID,
            'CUSTOMER_ID', CUSTOMER_ID,
            'CLAIM_DATE', CLAIM_DATE,
            'CLAIM_STATUS', CLAIM_STATUS,
            'CLAIM_AMOUNT', CLAIM_AMOUNT,
            'APPROVED_AMOUNT', APPROVED_AMOUNT,
            'SOURCE_FILE', SOURCE_FILE,
            'FILE_ROW_NUMBER', FILE_ROW_NUMBER
        ) AS REJECTION_DETAILS
    FROM INSURANCE_DB.STAGING.CLAIM_STAGING
    WHERE LOAD_BATCH_ID = $BATCH_ID
      AND STAGING_STATUS = 'REJECTED'
) AS S
ON  T.SOURCE_ENTITY = S.SOURCE_ENTITY
AND T.LOAD_BATCH_ID = S.LOAD_BATCH_ID
AND T.SOURCE_FILE = S.SOURCE_FILE
AND T.FILE_ROW_NUMBER = S.FILE_ROW_NUMBER
AND T.REJECTION_REASON = S.REJECTION_REASON

WHEN NOT MATCHED THEN INSERT (
    REJECTION_ID,
    SOURCE_ENTITY,
    LOAD_BATCH_ID,
    SOURCE_FILE,
    FILE_ROW_NUMBER,
    RECORD_ID,
    REJECTION_REASON,
    REJECTION_DETAILS,
    REJECTED_AT
)
VALUES (
    'REJ_' || UUID_STRING(),
    S.SOURCE_ENTITY,
    S.LOAD_BATCH_ID,
    S.SOURCE_FILE,
    S.FILE_ROW_NUMBER,
    S.RECORD_ID,
    S.REJECTION_REASON,
    S.REJECTION_DETAILS,
    CURRENT_TIMESTAMP()
);

